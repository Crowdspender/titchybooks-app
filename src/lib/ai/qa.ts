/**
 * Artifact-bound QA.
 *
 * Approval is bound to the exact immutable artifact set: the submission
 * revision, the render job, both PDF keys and their checksums. Structural
 * checks run against the pinned template scenes (not a fresh merge of mutable
 * template data) and against the PDF byte streams themselves.
 */

export type QaSeverity = "terminal" | "repair" | "transient";

export interface QaFinding {
  code: string;
  severity: QaSeverity;
  pageLabel: PageLabel | null;
  elementId: string | null;
  detail: string;
  expected?: string;
  actual?: string;
}

/** Coarse check summary kept for the status API and existing audit tooling. */
export interface QaCheck {
  id: string;
  passed: boolean;
  detail: string;
  severity: "terminal" | "retry";
}

export interface QaReport {
  passed: boolean;
  checks: QaCheck[];
  /** Structured, actionable findings. Optional so legacy reports stay valid. */
  findings?: QaFinding[];
  /** Artifact identity QA actually inspected. */
  artifact: {
    renderJobId: string | null;
    /** Submission revision the approved artifacts belong to. */
    submissionRevision: number;
    printSha256: string | null;
    readingSha256: string | null;
  } | null;
}

type TextEl = Extract<EditorElement, { type: "text" }>;
type ImageEl = Extract<EditorElement, { type: "image" }>;

function summarize(findings: QaFinding[], code: string): QaCheck | null {
  const matching = findings.filter((finding) => finding.code === code);
  if (matching.length === 0) return null;
  return {
    id: code,
    passed: false,
    detail: matching.map((finding) => finding.detail).slice(0, 3).join("; "),
    severity: matching.some((finding) => finding.severity === "terminal") ? "terminal" : "retry",
  };
}

/** True when a failed check should regenerate CONTENT rather than give up. */
export function isRetryable(report: QaReport): boolean {
  const findings = report.findings ?? [];
  if (findings.length > 0) {
    return findings.some((finding) => finding.severity === "repair" || finding.severity === "transient");
  }
  return report.checks.some((check) => !check.passed && check.severity === "retry");
}

/** True when nothing repairable remains but the book cannot be approved. */
export function hasTerminalFinding(report: QaReport): boolean {
  return (report.findings ?? []).some((finding) => finding.severity === "terminal");
}

/** Slot ids whose text should be regenerated by a targeted repair. */
export function repairableSlotIds(report: QaReport): Set<string> {
  return new Set(
    (report.findings ?? [])
      .filter((finding) => finding.severity === "repair" && finding.elementId)
      .map((finding) => finding.elementId as string),
  );
}

/** Feedback passed to the repair prompt: only repairable, slot-scoped findings. */
export function repairFeedback(report: QaReport): Array<{
  slotId: string | null;
  pageLabel: string | null;
  code: string;
  detail: string;
}> {
  return (report.findings ?? [])
    .filter((finding) => finding.severity === "repair")
    .map((finding) => ({
      slotId: finding.elementId,
      pageLabel: finding.pageLabel,
      code: finding.code,
      detail: finding.detail,
    }));
}

/**
 * Estimate whether a text element's content fits its box once wrapped.
 * Now backed by the shared layout engine: QA and rendering cannot disagree.
 */
export function estimateTextFits(el: TextEl): boolean {
  const metrics = measureTextBlock(el.text, Math.max(1, el.width), textStyleOf(el));
  return metrics.height <= el.height;
}

function textStyleOf(el: TextEl): TextStyle {
  return {
    fontSize: el.fontSize,
    fontWeight: el.fontWeight,
    letterSpacing: el.letterSpacing,
    lineHeight: el.lineHeight,
  };
}

function collectTexts(pages: Array<{ pageLabel: PageLabel; scene: EditorScene }>): Array<{ pageLabel: PageLabel; element: TextEl }> {
  return pages.flatMap((page) =>
    page.scene.elements
      .filter((element): element is TextEl => element.type === "text" && element.visible)
      .map((element) => ({ pageLabel: page.pageLabel, element })),
  );
}

function collectImages(pages: Array<{ pageLabel: PageLabel; scene: EditorScene }>): Array<{ pageLabel: PageLabel; element: ImageEl }> {
  return pages.flatMap((page) =>
    page.scene.elements
      .filter((element): element is ImageEl => element.type === "image" && element.visible)
      .map((element) => ({ pageLabel: page.pageLabel, element })),
  );
}

const MODERATION_CHUNK_CHARS = 2000;
const MODERATION_MAX_CHUNKS = 12;

/**
 * Moderate every generated text in bounded chunks. Returns `unavailable` when
 * the provider cannot answer, which must never be treated as a policy
 * rejection: an outage retries QA without rewriting safe content.
 */
async function moderateText(texts: string[]): Promise<"ok" | "flagged" | "unavailable"> {
  if (!isAIConfigured() || texts.length === 0) return "ok";
  const chunks: string[] = [];
  let current = "";
  for (const text of texts) {
    if (current.length > 0 && current.length + text.length > MODERATION_CHUNK_CHARS) {
      chunks.push(current);
      current = "";
    }
    // A single oversized text is split rather than truncated away.
    for (let offset = 0; offset < text.length; offset += MODERATION_CHUNK_CHARS) {
      const piece = text.slice(offset, offset + MODERATION_CHUNK_CHARS);
      if (current.length + piece.length > MODERATION_CHUNK_CHARS) {
        chunks.push(current);
        current = "";
      }
      current += `${piece}\n\n`;
    }
  }
  if (current.trim()) chunks.push(current);
  if (chunks.length > MODERATION_MAX_CHUNKS) return "unavailable";
  try {
    for (const chunk of chunks) {
      const result = await getOpenAIClient().moderations.create({
        model: "omni-moderation-latest",
        input: chunk,
      });
      if (result.results.some((entry) => entry.flagged)) return "flagged";
    }
    return "ok";
  } catch {
    return "unavailable";
  }
}

async function inspectArtifacts(
  submission: {
    id: string;
    revision: number;
    pdfS3Key: string | null;
    readingPdfS3Key: string | null;
    artifactManifest: unknown;
  },
  renderJobId: string | null,
): Promise<{ findings: QaFinding[]; manifest: ArtifactManifest | null }> {
  const findings: QaFinding[] = [];
  const manifest = parseArtifactManifest(submission.artifactManifest);
  if (!manifest) {
    findings.push({
      code: "artifact-manifest",
      severity: "terminal",
      pageLabel: null,
      elementId: null,
      detail: "The submission has no valid artifact manifest",
    });
    return { findings, manifest: null };
  }
  if (!manifestCoversSubmission(manifest, submission)) {
    findings.push({
      code: "artifact-manifest",
      severity: "terminal",
      pageLabel: null,
      elementId: null,
      detail: "The artifact manifest does not match the current submission revision or keys",
      expected: `revision ${submission.revision}`,
      actual: `revision ${manifest.submissionRevision}`,
    });
  }
  if (renderJobId && manifest.renderJobId !== renderJobId) {
    findings.push({
      code: "artifact-stale-render",
      severity: "terminal",
      pageLabel: null,
      elementId: null,
      detail: "The published artifacts came from a different render job",
      expected: renderJobId,
      actual: manifest.renderJobId,
    });
  }
  if (!submission.pdfS3Key || !submission.readingPdfS3Key) {
    findings.push({
      code: "artifact-missing",
      severity: "terminal",
      pageLabel: null,
      elementId: null,
      detail: "Both the print sheet and the reading PDF are required",
    });
    return { findings, manifest };
  }

  for (const kind of ["print", "reading"] as const) {
    const descriptor = manifest[kind];
    let bytes: Buffer;
    try {
      bytes = await downloadFromS3(descriptor.s3Key);
    } catch {
      findings.push({
        code: "artifact-missing",
        severity: "terminal",
        pageLabel: null,
        elementId: null,
        detail: `The ${kind} PDF could not be read from storage`,
      });
      continue;
    }
    const differences = await verifyArtifact(kind, descriptor, bytes);
    for (const difference of differences) {
      findings.push({
        code: difference.code,
        severity: "terminal",
        pageLabel: null,
        elementId: null,
        detail: `The ${kind} PDF is not the published artifact: ${difference.detail}`,
      });
    }
  }
  return { findings, manifest };
}

/**
 * Run the automated QA checklist that replaces the manual PENDING -> APPROVED
 * gate for AI-generated books. Every check is evaluated; `passed` is true only
 * when all checks pass.
 */
export async function runQaChecklist(
  submissionId: string,
  context: { concept?: string; renderJobId?: string | null } = {},
): Promise<QaReport> {
  const submission = await prisma.submission.findUnique({ where: { id: submissionId } });
  if (!submission) {
    return {
      passed: false,
      checks: [{ id: "artifact-manifest", passed: false, detail: "Submission not found", severity: "terminal" }],
      findings: [
        {
          code: "submission-missing",
          severity: "terminal",
          pageLabel: null,
          elementId: null,
          detail: "Submission not found",
        },
      ],
      artifact: null,
    };
  }

  const findings: QaFinding[] = [];
  const artifacts = await inspectArtifacts(submission, context.renderJobId ?? null);
  findings.push(...artifacts.findings);

  // Title limit.
  if (submission.title && submission.title.length > 120) {
    findings.push({
      code: "title-length",
      severity: "repair",
      pageLabel: "FRONT_COVER",
      elementId: null,
      detail: `Title is ${submission.title.length} characters, the maximum is 120`,
    });
  }

  // Pages: mergedPages() applies the pinned template scenes for AI books.
  let pages: Array<{ pageLabel: PageLabel; scene: EditorScene }> = [];
  let pagesOk = true;
  try {
    pages = await prisma.$transaction((tx) => mergedPages(tx, submission));
  } catch (error) {
    pagesOk = false;
    findings.push({
      code: "pages-complete",
      severity: "terminal",
      pageLabel: null,
      elementId: null,
      detail: error instanceof Error ? error.message : "Page merge failed",
    });
  }

  const pinned = parsePinnedTemplate(submission.pinnedTemplate);
  const generatedIds = pinned ? new Set(generatedSlots(pinned.manifest).map((slot) => slot.id)) : null;
  const texts = collectTexts(pages);
  const generatedTexts = generatedIds
    ? texts.filter((entry) => generatedIds.has(entry.element.id))
    : texts;

  if (pagesOk) {
    // Required page coverage: every page needs generated content.
    for (const pageLabel of PAGE_LABELS) {
      const pageTexts = generatedTexts.filter((entry) => entry.pageLabel === pageLabel);
      const nonEmpty = pageTexts.filter((entry) => entry.element.text.trim().length > 0);
      if (nonEmpty.length === 0) {
        findings.push({
          code: "missing-page-content",
          severity: "repair",
          pageLabel,
          elementId: pageTexts[0]?.element.id ?? null,
          detail: `Page ${pageLabel} has no generated content`,
        });
      }
    }
    if (generatedIds) {
      for (const slot of generatedSlots(pinned!.manifest)) {
        if (!slot.required) continue;
        const rendered = texts.find((entry) => entry.element.id === slot.id && entry.pageLabel === slot.pageLabel);
        if (!rendered || rendered.element.text.trim().length === 0) {
          findings.push({
            code: "missing-required-slot",
            severity: "repair",
            pageLabel: slot.pageLabel,
            elementId: slot.id,
            detail: `Required slot "${slot.id}" has no content`,
          });
        }
      }
    }
  }

  for (const { pageLabel, element } of generatedTexts) {
    if (element.text.trim().length === 0) {
      findings.push({
        code: "empty-text",
        severity: "repair",
        pageLabel,
        elementId: element.id,
        detail: `Element "${element.id}" is empty`,
      });
      continue;
    }
    const placeholder = describePlaceholderText(element.text);
    if (placeholder) {
      findings.push({
        code: `placeholder-${placeholder.code}`,
        severity: "repair",
        pageLabel,
        elementId: element.id,
        detail: `Element "${element.id}": ${placeholder.detail}`,
      });
      continue;
    }
    const unsupported = findUnsupportedCharacters(element.text);
    if (unsupported.length > 0) {
      findings.push({
        code: "unsupported-glyph",
        severity: "repair",
        pageLabel,
        elementId: element.id,
        detail: `Element "${element.id}" contains unsupported character(s): ${unsupported.join(" ")}`,
      });
      continue;
    }
    const metrics = measureTextBlock(element.text, element.width, textStyleOf(element));
    if (metrics.height > element.height) {
      findings.push({
        code: "text-fits",
        severity: "repair",
        pageLabel,
        elementId: element.id,
        detail: `Element "${element.id}" needs ${Math.round(metrics.height)}px but its box is ${Math.round(element.height)}px`,
        expected: `${Math.round(element.height)}px`,
        actual: `${Math.round(metrics.height)}px`,
      });
    }
    if (metrics.maxLineWidth > element.width) {
      findings.push({
        code: "text-width",
        severity: "repair",
        pageLabel,
        elementId: element.id,
        detail: `Element "${element.id}" has a line wider than its box`,
        expected: `${Math.round(element.width)}px`,
        actual: `${Math.round(metrics.maxLineWidth)}px`,
      });
    }
  }

  // Layout: generated text must stay inside the safe page area and out of the
  // reserved back-cover branding strip.
  for (const { pageLabel, element } of generatedTexts) {
    const box: Rect = { x: element.x, y: element.y, width: element.width, height: element.height };
    if (!isBoxInsidePage(box)) {
      findings.push({
        code: "page-safe-area",
        severity: "terminal",
        pageLabel,
        elementId: element.id,
        detail: `Element "${element.id}" is outside the printable page area`,
      });
    }
    const reserved = brandingRegion(pageLabel);
    if (reserved && rectsOverlap(box, reserved)) {
      findings.push({
        code: "branding-overlap",
        severity: "terminal",
        pageLabel,
        elementId: element.id,
        detail: `Element "${element.id}" overlaps the reserved back-cover branding strip`,
      });
    }
  }

  // Images: dimensions must be known and the effective DPI must clear the
  // qualified profile's minimum. Unknown dimensions block approval outright.
  const images = collectImages(pages);
  if (images.length > 0) {
    const assetIds = [...new Set(images.map((entry) => entry.element.assetId))];
    const assets = await prisma.asset.findMany({ where: { id: { in: assetIds } } });
    const byId = new Map(assets.map((asset) => [asset.id, asset]));
    for (const { pageLabel, element } of images) {
      const asset = byId.get(element.assetId);
      if (!asset) {
        findings.push({
          code: "image-missing",
          severity: "terminal",
          pageLabel,
          elementId: element.id,
          detail: `Image "${element.id}" references a missing asset`,
        });
        continue;
      }
      if (!asset.width || !asset.height) {
        findings.push({
          code: "image-dimensions-unknown",
          severity: "terminal",
          pageLabel,
          elementId: element.id,
          detail: `Image "${element.id}" has unknown pixel dimensions`,
        });
        continue;
      }
      // Resolve the physical page width from the reading profile, so the DPI
      // figure describes the printed book rather than the imposition sheet.
      const dpi = Math.min(
        calculateImageElementDpi(element.width, element.crop.scaleX, asset.width, 74),
        calculateImageElementDpi(element.height, element.crop.scaleY, asset.height, 105),
      );
      if (dpi < MIN_EFFECTIVE_DPI) {
        findings.push({
          code: "image-resolution",
          severity: "terminal",
          pageLabel,
          elementId: element.id,
          detail: `Image "${element.id}" prints at ${Math.round(dpi)} DPI, below ${MIN_EFFECTIVE_DPI}`,
          expected: `${MIN_EFFECTIVE_DPI} DPI`,
          actual: `${Math.round(dpi)} DPI`,
        });
      }
    }
  }

  // Content policy: moderate the prompt and every generated text.
  const generatedStrings = generatedTexts.map((entry) => entry.element.text).filter((text) => text.trim().length > 0);
  const moderation = await moderateText([context.concept ?? "", ...generatedStrings].filter(Boolean));
  if (moderation === "flagged") {
    findings.push({
      code: "content-policy",
      severity: "terminal",
      pageLabel: null,
      elementId: null,
      detail: "Content was flagged by moderation",
    });
  } else if (moderation === "unavailable") {
    findings.push({
      code: "moderation-unavailable",
      severity: "transient",
      pageLabel: null,
      elementId: null,
      detail: "Moderation is temporarily unavailable; the book was not approved",
    });
  }

  // Coarse checks for the status API, derived from the findings.
  const checks: QaCheck[] = [];
  const allCodes = [...new Set(findings.map((finding) => finding.code))];
  for (const code of allCodes) {
    const summary = summarize(findings, code);
    if (summary) checks.push(summary);
  }
  for (const passedCode of ["artifact-checksum", "pages-complete", "content-policy"]) {
    if (!allCodes.includes(passedCode)) {
      checks.push({ id: passedCode, passed: true, detail: "Passed", severity: "terminal" });
    }
  }

  return {
    passed: findings.length === 0,
    checks,
    findings,
    artifact: artifacts.manifest
      ? {
          renderJobId: artifacts.manifest.renderJobId,
          submissionRevision: artifacts.manifest.submissionRevision,
          printSha256: artifacts.manifest.print.sha256,
          readingSha256: artifacts.manifest.reading.sha256,
        }
      : null,
  };
}
